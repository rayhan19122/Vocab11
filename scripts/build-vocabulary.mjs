// Builds src/data/vocabulary.js from:
//   data-source/pdf-source.json  (words + original sentences transcribed from the PDF)
//   data-source/content.txt      (meaning, 3 synonyms, antonyms, difficulty, related flag)
//   data-source/term-examples.txt (an example sentence for every synonym and antonym)
// Usage: node scripts/build-vocabulary.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pdf = JSON.parse(readFileSync(join(root, 'data-source/pdf-source.json'), 'utf8')).lectures
const levels = { e: 'easy', m: 'medium', h: 'hard' }

const content = new Map()
for (const raw of readFileSync(join(root, 'data-source/content.txt'), 'utf8').split('\n')) {
  const line = raw.trim()
  if (!line || line.startsWith('#')) continue
  const [word, meaning, syn, ant, diff, flag] = line.split('|').map((part) => part.trim())
  const list = (text) => (text ? text.split(';').map((item) => item.trim()).filter(Boolean) : [])
  if (content.has(word)) throw new Error(`Duplicate content row for "${word}"`)
  content.set(word, { meaning, synonyms: list(syn), antonyms: list(ant), difficulty: levels[diff], related: flag === 'R' })
}

// Example sentences: "Word | term: sentence | term: sentence ..." (synonyms first, then antonyms).
const termExamples = new Map()
for (const raw of readFileSync(join(root, 'data-source/term-examples.txt'), 'utf8').split('\n')) {
  const line = raw.trim()
  if (!line || line.startsWith('#')) continue
  const [word, ...items] = line.split(' | ')
  const pairs = items.map((item) => {
    const split = item.indexOf(': ')
    if (split < 1) throw new Error(`Bad example item "${item}" for "${word}"`)
    return [item.slice(0, split).trim(), item.slice(split + 2).trim()]
  })
  if (termExamples.has(word)) throw new Error(`Duplicate example row for "${word}"`)
  termExamples.set(word, pairs)
}

const pad = (n) => String(n).padStart(2, '0')
const entries = []
for (const lecture of Object.keys(pdf).map(Number).sort((a, b) => a - b)) {
  pdf[lecture].forEach(([word, example], index) => {
    const extra = content.get(word)
    if (!extra) throw new Error(`No content row for "${word}" (Lecture ${lecture})`)
    content.delete(word)
    const pairs = termExamples.get(word)
    if (!pairs) throw new Error(`No example sentences for "${word}"`)
    const expected = [...extra.synonyms, ...extra.antonyms]
    if (pairs.map(([term]) => term).join('|') !== expected.join('|')) {
      throw new Error(`Example terms for "${word}" do not match content.txt: expected [${expected.join(', ')}], got [${pairs.map(([term]) => term).join(', ')}]`)
    }
    termExamples.delete(word)
    entries.push({
      id: `l${pad(lecture)}-w${pad(index + 1)}`,
      lecture,
      word,
      meaning: extra.meaning,
      synonyms: extra.synonyms,
      antonyms: extra.antonyms,
      related: extra.related,
      example,
      termExamples: Object.fromEntries(pairs),
      difficulty: extra.difficulty,
    })
  })
}
if (termExamples.size) throw new Error(`Example rows with no PDF word: ${[...termExamples.keys()].join(', ')}`)
if (content.size) throw new Error(`Content rows with no PDF word: ${[...content.keys()].join(', ')}`)

const body = entries.map((entry) => `  ${JSON.stringify(entry)},`).join('\n')
const out = `// GENERATED by scripts/build-vocabulary.mjs from data-source/. Edit the sources, then re-run the script.
// Words and example sentences come verbatim from "11 Lectures .pdf".
// example is the PDF sentence. termExamples maps each synonym/antonym to a sentence written for this app (not from the PDF).
// related: true means the 3 synonyms are the closest equivalents/related words (the word has no true synonyms).

export const vocabulary = [
${body}
]

export const lectures = Array.from({ length: 11 }, (_, index) => ({
  id: index + 1,
  name: \`Lecture \${String(index + 1).padStart(2, '0')}\`,
  words: vocabulary.filter((item) => item.lecture === index + 1).length,
}))

export const vocabularyById = Object.fromEntries(vocabulary.map((item) => [item.id, item]))
`
writeFileSync(join(root, 'src/data/vocabulary.js'), out)
console.log(`Wrote ${entries.length} entries to src/data/vocabulary.js`)
